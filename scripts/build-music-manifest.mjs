import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const musicDir = path.join(root, 'assets', 'music');
const manifestFile = path.join(root, 'src', 'data', 'bundled-music.js');
const serviceWorkerFile = path.join(root, 'sw.js');
const supported = new Set(['.mp3', '.m4a', '.ogg', '.wav', '.flac', '.aac']);
const stationIds = ['loner-village', 'loner-forest', 'bandit-atp', 'military-network'];

fs.mkdirSync(musicDir, { recursive: true });
function collectAudioFiles(directory, prefix = '') {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const relative = path.join(prefix, entry.name);
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return collectAudioFiles(absolute, relative);
    return entry.isFile() && supported.has(path.extname(entry.name).toLowerCase()) ? [relative] : [];
  });
}
const files = collectAudioFiles(musicDir).sort((a, b) => a.localeCompare(b, 'ru'));

const tracks = files.map((fileName, index) => {
  const title = path.basename(fileName, path.extname(fileName)).replace(/[._]+/g, ' ').trim();
  const id = `bundled-${Buffer.from(fileName).toString('hex').slice(0, 24)}`;
  const relative = `../../assets/music/${fileName.split(path.sep).map(encodeURIComponent).join('/')}`;
  const size = fs.statSync(path.join(musicDir, fileName)).size;
  return {
    id,
    title: title || `Композиция ${index + 1}`,
    artist: 'Музыкальная библиотека Зоны',
    fileName,
    size,
    url: relative,
    stations: stationIds
  };
});

const js = `// Generated by scripts/build-music-manifest.mjs. Do not edit by hand.\nexport const BUNDLED_MUSIC_TRACKS = [\n${tracks.map(track => `  { id: ${JSON.stringify(track.id)}, title: ${JSON.stringify(track.title)}, artist: ${JSON.stringify(track.artist)}, fileName: ${JSON.stringify(track.fileName)}, size: ${track.size}, url: new URL(${JSON.stringify(track.url)}, import.meta.url).href, stations: ${JSON.stringify(track.stations)} }`).join(',\n')}\n];\n`;
fs.writeFileSync(manifestFile, js, 'utf8');

let sw = fs.readFileSync(serviceWorkerFile, 'utf8');
const start = sw.indexOf('const APP_SHELL = [');
const end = sw.indexOf('\n];', start);
if (start < 0 || end < 0) throw new Error('Could not find APP_SHELL in sw.js');
const existing = new Set([...sw.slice(start, end).matchAll(/"(\.\/[^\"]+)"/g)].map(match => match[1]));
const audioEntries = files.map(file => `  ${JSON.stringify(`./assets/music/${file.split(path.sep).map(encodeURIComponent).join('/')}`)},`)
  .filter(line => !existing.has(JSON.parse(line.trim().replace(/,$/, ''))));
if (audioEntries.length) sw = `${sw.slice(0, end)}\n${audioEntries.join('\n')}${sw.slice(end)}`;
fs.writeFileSync(serviceWorkerFile, sw, 'utf8');

console.log(`Music manifest generated: ${tracks.length} bundled audio file(s).`);
